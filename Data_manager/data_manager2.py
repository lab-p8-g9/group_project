# ---------------- VALIDATION ----------------

def validate_complaint(complaint): #for own usage 
    if not isinstance(complaint, dict):
        raise TypeError("Complaint must be a dictionary.")

    required = (
        "ComplaintID",
        "Address",
        "Category",
        "PriorityScore",
        "UpdatedScore",
        "Status"
    )

    for field in required:
        if field not in complaint:
            raise ValueError(f"Missing required field: {field}")

    if type(complaint["ComplaintID"]) is not int:
        raise ValueError("ComplaintID must be an integer.")

    if complaint["ComplaintID"] <= 0:
        raise ValueError("ComplaintID must be positive.")

    for field in ("PriorityScore", "UpdatedScore"):
        score = complaint[field]

        if type(score) is not int or not 1 <= score <= 8:
            raise ValueError(
                f"{field} must be an integer between 1 and 8."
            )

    if complaint["Status"] not in ("Resolved", "Unresolved"):
        raise ValueError("Invalid complaint status.")

    if (not isinstance(complaint["Address"], str) or not complaint["Address"].strip()):
        raise ValueError("Invalid email address.")

    if (not isinstance(complaint["Category"], str) or not complaint["Category"].strip()):
        raise ValueError("Invalid complaint category.")

    return True

# ---------------- JSON OPERATIONS ----------------

def save_to_JSON(department, complaints): #for own usage 
    if department not in JSON_FILES:
        raise ValueError("Invalid department.")

    if not isinstance(complaints, list):
        raise TypeError("Complaints must be a list.")

    if len(complaints) > 10:
        raise ValueError("Cannot save more than 10 complaints.")

    for complaint in complaints:
        if not isinstance(complaint, dict):
            raise TypeError("Each complaint must be a dictionary.")

        validate_complaint(complaint)

    filename = JSON_FILES[department]
    temp_name = None

    try:
        with tempfile.NamedTemporaryFile(
            mode="w",
            encoding="utf-8",
            dir=str(filename.parent),
            suffix=".tmp",
            delete=False
        ) as file:
            temp_name = file.name
            json.dump(complaints, file, indent=4)

        os.replace(temp_name, filename)
        return True

    except OSError as error:
        print(f"Error saving JSON: {error}")
        return False

    finally:
        if temp_name is not None:
            try:
                os.remove(temp_name)
            except FileNotFoundError:
                pass
            except OSError as error:
                print(f"Temporary file cleanup warning: {error}")

def load_from_JSON(department): # 'Admin' or 'Tech'
    if department not in JSON_FILES:
        raise ValueError("Invalid department.")

    filename = JSON_FILES[department]

    try:
        with open(filename, "r", encoding="utf-8") as file:
            complaints = json.load(file)

        if not isinstance(complaints, list):
            raise ValueError("JSON must contain a list.")

        if len(complaints) > 10:
            raise ValueError("JSON contains more than 10 complaints.")

        for complaint in complaints:
            if not isinstance(complaint, dict):
                raise ValueError(
                    "Each complaint must be a dictionary."
                )

            validate_complaint(complaint)

        return complaints

    except FileNotFoundError:
        return []

    except (OSError, ValueError, TypeError) as error:
        print(f"Error loading JSON: {error}")
        return None

def refresh_top_10(department): #for own usage 
    tables = {
        "Admin": "Admin_Team",
        "Tech": "Tech_Professionals"
    }

    if department not in tables:
        raise ValueError("Invalid department.")

    table = tables[department]

    try:
        c.execute(f"""
            SELECT *
            FROM {table}
            WHERE Status = 'Unresolved'
            ORDER BY UpdatedScore DESC,
                     Datetime ASC,
                     ComplaintID ASC
            LIMIT 10
        """)

        columns = [column[0] for column in c.description]

        complaints = [
            dict(zip(columns, row))
            for row in c.fetchall()
        ]

        return save_to_JSON(department, complaints)

    except sqlite3.DatabaseError as error:
        print(f"Error refreshing top 10: {error}")
        return False

